import * as fs from 'fs';
import * as path from 'path';

export class DocsGenerator {
  private rootDir: string;
  private codemapDir: string;
  private docsDir: string;

  constructor(rootDir: string) {
    this.rootDir = path.resolve(rootDir);
    this.codemapDir = path.join(this.rootDir, '.codemap');
    this.docsDir = path.join(this.rootDir, 'docs');
  }

  public generateDocs(): void {
    if (!fs.existsSync(this.codemapDir)) {
      throw new Error('No .codemap/ found. Please run "codeatlas scan" first.');
    }

    if (!fs.existsSync(this.docsDir)) {
      fs.mkdirSync(this.docsDir, { recursive: true });
    }

    // Read codemap files
    const summaryPath = path.join(this.codemapDir, 'project-summary.md');
    const archPath = path.join(this.codemapDir, 'architecture.md');
    const techPath = path.join(this.codemapDir, 'technology-stack.json');

    const summary = fs.existsSync(summaryPath) ? fs.readFileSync(summaryPath, 'utf8') : '# Project Summary';
    const architecture = fs.existsSync(archPath) ? fs.readFileSync(archPath, 'utf8') : '# Architecture';
    const tech = fs.existsSync(techPath) ? JSON.parse(fs.readFileSync(techPath, 'utf8')) : {};

    // 1. Generate docs/index.md
    const indexContent = `# CodeAtlas Documentation Site

Welcome to the automated documentation generated by **CodeAtlas**.

## Navigation
- [Project Overview](./overview.md)
- [Architecture & Diagrams](./architecture.md)
- [Technology Stack](./tech-stack.md)

---
*Generated automatically by CodeAtlas.*
`;
    fs.writeFileSync(path.join(this.docsDir, 'index.md'), indexContent, 'utf8');

    // 2. Generate docs/overview.md
    fs.writeFileSync(path.join(this.docsDir, 'overview.md'), summary, 'utf8');

    // 3. Generate docs/architecture.md
    fs.writeFileSync(path.join(this.docsDir, 'architecture.md'), architecture, 'utf8');

    // 4. Generate docs/tech-stack.md
    const techContent = `# Technology Stack

\`\`\`json
${JSON.stringify(tech, null, 2)}
\`\`\`
`;
    fs.writeFileSync(path.join(this.docsDir, 'tech-stack.md'), techContent, 'utf8');
  }
}
