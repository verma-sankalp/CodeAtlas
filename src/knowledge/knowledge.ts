import * as fs from 'fs';
import * as path from 'path';
import { ScannedFile } from '../scanner/scanner.js';
import { ProjectProfile } from '../detectors/detector.js';
import { ParseResult } from '../parsers/parser.js';
import { DependencyGraph } from '../graph/graph.js';

export class KnowledgeManager {
  private rootDir: string;
  private codemapDir: string;

  constructor(rootDir: string) {
    this.rootDir = path.resolve(rootDir);
    this.codemapDir = path.join(this.rootDir, '.codemap');
  }

  public saveKnowledge(
    files: ScannedFile[],
    profile: ProjectProfile,
    parseResults: ParseResult[],
    graph: DependencyGraph
  ): void {
    if (!fs.existsSync(this.codemapDir)) {
      fs.mkdirSync(this.codemapDir, { recursive: true });
    }

    // 1. file-index.json
    fs.writeFileSync(
      path.join(this.codemapDir, 'file-index.json'),
      JSON.stringify(files, null, 2),
      'utf8'
    );

    // 2. dependency-graph.json
    fs.writeFileSync(
      path.join(this.codemapDir, 'dependency-graph.json'),
      JSON.stringify(graph.getGraphData(), null, 2),
      'utf8'
    );

    // 3. technology-stack.json
    fs.writeFileSync(
      path.join(this.codemapDir, 'technology-stack.json'),
      JSON.stringify(profile, null, 2),
      'utf8'
    );

    // 4. architecture.md
    const mermaid = graph.generateMermaidDiagram();
    const archContent = `# Architecture Map

Generated by CodeAtlas.

## Technology Stack
- **Languages:** ${profile.languages.join(', ')}
- **Frameworks:** ${profile.frameworks.length ? profile.frameworks.join(', ') : 'None detected'}
- **Entry Points:** ${profile.entryPoints.join(', ') || 'None detected'}

## Dependency Flow (Mermaid)
\`\`\`mermaid
${mermaid}
\`\`\`
`;
    fs.writeFileSync(path.join(this.codemapDir, 'architecture.md'), archContent, 'utf8');

    // 5. project-summary.md
    const summaryContent = `# Project Summary

**Tagline:** Understand any codebase. Find anything. Change with confidence.

## Overview
- **Total Files Scanned:** ${files.length}
- **Primary Languages:** ${profile.languages.join(', ')}
- **Frameworks:** ${profile.frameworks.join(', ') || 'Vanilla / Standard'}
- **Manifests:** ${profile.manifests.join(', ') || 'None'}

## Key Directories
${profile.directories.frontend ? `- **Frontend:** ${profile.directories.frontend.join(', ')}` : ''}
${profile.directories.backend ? `- **Backend:** ${profile.directories.backend.join(', ')}` : ''}
${profile.directories.database ? `- **Database:** ${profile.directories.database.join(', ')}` : ''}
${profile.directories.tests ? `- **Tests:** ${profile.directories.tests.join(', ')}` : ''}

## Important Entry Points
${profile.entryPoints.map(ep => `- \`${ep}\``).join('\n') || '- None identified'}
`;
    fs.writeFileSync(path.join(this.codemapDir, 'project-summary.md'), summaryContent, 'utf8');
  }

  public hasKnowledge(): boolean {
    return fs.existsSync(path.join(this.codemapDir, 'project-summary.md'));
  }
}
